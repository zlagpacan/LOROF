	task check_outputs();
	begin
		expected_packet_now = {expected_out_valid, expected_out_dest_pr, expected_out_rob_idx,
			expected_out_result_d, expected_out_except};
		if (delay_fast_outputs) begin
			expected_packet_check = expected_packet_d3;
			expected_packet_d3 = expected_packet_d2;
			expected_packet_d2 = expected_packet_d1;
			expected_packet_d1 = expected_packet_now;
		end
		else if (delay_slow_outputs) begin
			expected_packet_check = expected_packet_slow_d1;
			expected_packet_slow_d1 = expected_packet_now;
		end
		else expected_packet_check = expected_packet_now;
		if (expected_in_ready !== DUT_in_ready) begin
			$display("TB ERROR: expected_in_ready (%b) != DUT_in_ready (%b)", expected_in_ready, DUT_in_ready);
			num_errors++; tb_error = 1'b1;
		end
		if (expected_packet_check.valid !== DUT_out_valid) begin
			$display("TB ERROR: expected_out_valid (%b) != DUT_out_valid (%b)", expected_packet_check.valid, DUT_out_valid);
			num_errors++; tb_error = 1'b1;
		end
		if (expected_packet_check.dest_pr !== DUT_out_dest_pr) begin
			$display("TB ERROR: expected_out_dest_pr (%h) != DUT_out_dest_pr (%h)", expected_packet_check.dest_pr, DUT_out_dest_pr);
			num_errors++; tb_error = 1'b1;
		end
		if (expected_packet_check.rob_idx !== DUT_out_rob_idx) begin
			$display("TB ERROR: expected_out_rob_idx (%h) != DUT_out_rob_idx (%h)", expected_packet_check.rob_idx, DUT_out_rob_idx);
			num_errors++; tb_error = 1'b1;
		end
		if (expected_packet_check.result_d !== DUT_out_result_d) begin
			$display("TB ERROR: expected_result (%h) != DUT_result (%h)", expected_packet_check.result_d, DUT_out_result_d);
			num_errors++; tb_error = 1'b1;
		end
		if (expected_packet_check.except !== DUT_out_except) begin
			$display("TB ERROR: expected_except (%b) != DUT_except (%b)", expected_packet_check.except, DUT_out_except);
			num_errors++; tb_error = 1'b1;
		end
		#(PERIOD/10);
		tb_error = 1'b0;
	end
	endtask

